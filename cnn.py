import os
import pathlib
import tensorflow as tf
from tensorflow.keras import layers, models

# 1. Download the flower dataset
print("Downloading plant data...")
_url = "https://storage.googleapis.com/download.tensorflow.org/example_images/flower_photos.tgz"
path_to_tar = tf.keras.utils.get_file('flower_photos', origin=_url, untar=True)
DOWNLOAD_DIR = pathlib.Path(path_to_tar)

# Ensure DATA_DIR points exactly to the directory containing the 5 category subfolders
if (DOWNLOAD_DIR / 'flower_photos').exists():
    DATA_DIR = DOWNLOAD_DIR / 'flower_photos'
else:
    DATA_DIR = DOWNLOAD_DIR

print(f"Target dataset directory: {DATA_DIR}")

# 2. Load training data with all classes detected
print("Reading images...")
train_ds = tf.keras.utils.image_dataset_from_directory(
    DATA_DIR,
    validation_split=0.2,
    subset="training",
    seed=123,
    image_size=(180, 180),
    batch_size=32)

class_names = train_ds.class_names
print("Detected classes:", class_names)

# Save our correct category list to classes.txt for the UI and other evaluations
with open("classes.txt", "w") as f:
    for item in class_names:
        f.write(f"{item}\n")

# 3. Build the CNN targeting 5 output classes
model = models.Sequential([
    layers.Input(shape=(180, 180, 3)),
    layers.Rescaling(1./255),

    layers.Conv2D(16, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dense(len(class_names), activation='softmax')
])

model.compile(optimizer='adam',
              loss='sparse_categorical_crossentropy',
              metrics=['accuracy'])

# 4. Train
print("Training model on all categories...")
model.fit(train_ds, epochs=3)
model.save("flower_model.keras")
print("\n🎉 Training finished! Model saved as 'flower_model.keras'")

