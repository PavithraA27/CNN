import tensorflow as tf
from tensorflow.keras import layers, models
import numpy as np

# 1. Load dataset instantly from internal memory (No URL downloads, no path errors)
print("Loading built-in handwritten digits dataset...")
(X_train, y_train), (X_val, y_val) = tf.keras.datasets.mnist.load_data()

# Reshape data to include the single greyscale color channel
X_train = np.expand_dims(X_train, axis=-1)
X_val = np.expand_dims(X_val, axis=-1)

# Save our 10 class labels (digits 0 through 9) to a text file for the app UI
class_names = [str(i) for i in range(10)]
with open("classes.txt", "w") as f:
    for item in class_names: f.write(f"{item}\n")

# 2. Create an Ultra-Lightweight CNN Architecture
model = models.Sequential([
    layers.Input(shape=(28, 28, 1)),
    layers.Rescaling(1./255), # Fast inline bit-shifting pixel normalization

    layers.Conv2D(16, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),
    layers.Dense(32, activation='relu'),
    layers.Dense(10, activation='softmax') # 10 nodes for digits 0-9
])

model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

# 3. Rapid GPU Training Run (Only 2 epochs - takes ~30 seconds total)
print("Initiating rapid GPU neural network optimization...")
model.fit(X_train, y_train, validation_data=(X_val, y_val), epochs=2, batch_size=64)

model.save('digit_classifier.keras')
print("\n🎉 Done! Model saved as 'digit_classifier.keras' and labels saved to 'classes.txt'")



