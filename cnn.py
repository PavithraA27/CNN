import os
import tensorflow as tf
from tensorflow.keras import layers, models

# 1. Download official open-access TensorFlow Plant/Flower Dataset
print("Downloading optimized plant image dataset...")
_url = "https://googleapis.com"
path_to_tar = tf.keras.utils.get_file('flower_photos.tar.gz', origin=_url, extract=True)

# Point directly to where the subfolders are stored on the disk
DATA_DIR = os.path.join(os.path.dirname(path_to_tar), 'flower_photos')

# 2. Fast Streaming Data Loaders (180x180 pixels for rapid processing)
print("Setting up plant image loaders...")
train_ds = tf.keras.utils.image_dataset_from_directory(
    DATA_DIR, validation_split=0.2, subset="training", seed=123, image_size=(180, 180), batch_size=32)
val_ds = tf.keras.utils.image_dataset_from_directory(
    DATA_DIR, validation_split=0.2, subset="validation", seed=123, image_size=(180, 180), batch_size=32)

# Save our categories to a text file for the web interface
class_names = train_ds.class_names
with open("classes.txt", "w") as f:
    for item in class_names: f.write(f"{item}\n")

# 3. Create a Fast, Modern CNN Architecture
model = models.Sequential([
    layers.Input(shape=(180, 180, 3)),
    layers.Rescaling(1./255), # Normalize pixel colors instantly

    layers.Conv2D(16, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dense(len(class_names), activation='softmax')
])

model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

# 4. Rapid GPU Training Run (Only 3 epochs to finish under 2 minutes)
print("Initiating rapid GPU plant model training...")
model.fit(train_ds, validation_data=val_ds, epochs=3)
model.save('plant_classifier.keras')
print("\n🎉 Success! Model saved as 'plant_classifier.keras' and labels saved to 'classes.txt'")

